"""Pre-registered start-up priming test (ADR 0009 B): live pipeline, primed vs cold.

* P1: alarm events starting in the first ``window`` test steps drop by at least 50%.
* P2: composite F1 non-inferiority: paired bootstrap over channels, lower 95% bound of
  (primed − cold) above −0.03.
"""

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from sathealth.config import Config
from sathealth.evaluation.aggregate import composite_counts, paired_composite_delta
from sathealth.pipeline.decide import decide
from sathealth.pipeline.prepare import load_prepared, run_dir_for

P1_MIN_REDUCTION = 0.5
P2_MARGIN = -0.03


def _early_events(run_dir: Path, window: int, config: Config) -> dict[str, int]:
    total = labelled = 0
    for path in sorted((run_dir / "events").glob("*.json")):
        segments = load_prepared(run_dir_for(config), path.stem).segments
        for event in json.loads(path.read_text()):
            if event["start"] < window:
                total += 1
                labelled += any(
                    s.start <= event["end"] and s.end >= event["start"] for s in segments
                )
    return {"events": total, "overlapping_a_label": labelled}


def compare_priming(cold: Config, primed: Config) -> dict[str, Any]:
    runs = {"cold": decide(cold), "primed": decide(primed)}
    window = cold.deep.lstm.window
    early = {k: _early_events(r.run_dir, window, cold) for k, r in runs.items()}
    rows = {
        k: sorted(
            json.loads((r.run_dir / "per_channel.json").read_text()), key=lambda c: c["chan_id"]
        )
        for k, r in runs.items()
    }
    paired = paired_composite_delta(
        composite_counts(rows["primed"]),
        composite_counts(rows["cold"]),
        bootstrap=cold.evaluation.bootstrap,
        seed=cold.seed,
    )
    reduction = 1 - early["primed"]["events"] / max(early["cold"]["events"], 1)
    overall = {k: r.summary["subsets"]["all"] for k, r in runs.items()}
    return {
        "window": window,
        "early": early,
        "reduction": reduction,
        "composite_f1": {k: v["composite_f1"] for k, v in overall.items()},
        "fp_events_per_1k_steps": {k: v["fp_events_per_1k_steps"] for k, v in overall.items()},
        "event_f1": {k: v["event"]["f1"] for k, v in overall.items()},
        "delta": paired["delta"],
        "ci95": paired["ci95"],
        "P1": reduction >= P1_MIN_REDUCTION,
        "P2": paired["ci95"] is not None and paired["ci95"][0] > P2_MARGIN,
        "runs": {k: r.run_dir.name for k, r in runs.items()},
    }


def _change(reduction: float) -> str:
    return f"{reduction:.0%} fewer" if reduction >= 0 else f"{-reduction:.0%} more"


def render_priming(r: dict[str, Any]) -> str:
    word = {True: "**supported**", False: "**not supported**"}
    e = r["early"]
    ci = r["ci95"]
    return "\n".join(
        [
            "# Start-up priming: SMAP & MSL",
            "",
            f"_Generated by `sathealth priming` on {datetime.now(UTC):%Y-%m-%d}. Do not edit by "
            "hand. Pre-registered in [ADR 0009](adr/0009-extensions-and-confirmation.md)._",
            "",
            "Live pipeline (`configs/live.yaml`), every split scored cold vs after the last 256 "
            "steps of the nominal history before it (`configs/primed.yaml`). Models are identical.",
            "",
            "| | Hypothesis | Result | Verdict |",
            "|---|---|---|---|",
            f"| P1 | Events starting in the first {r['window']} test steps drop by ≥ 50% | "
            f"{e['cold']['events']} → {e['primed']['events']} ({_change(r['reduction'])}); "
            f"overlapping a label: {e['cold']['overlapping_a_label']} → "
            f"{e['primed']['overlapping_a_label']} | {word[r['P1']]} |",
            f"| P2 | Composite F1 not worse by more than 0.03 | "
            f"{r['composite_f1']['cold']:.3f} → {r['composite_f1']['primed']:.3f}, "
            f"Δ {r['delta']:+.3f} [{ci[0]:+.3f}, {ci[1]:+.3f}] (paired over channels) | "
            f"{word[r['P2']]} |",
            "",
            f"False events per 1k steps: {r['fp_events_per_1k_steps']['cold']:.2f} → "
            f"{r['fp_events_per_1k_steps']['primed']:.2f}. Event F1: "
            f"{r['event_f1']['cold']:.3f} → {r['event_f1']['primed']:.3f}.",
            "",
        ]
    )


def write_priming(cold: Config, primed: Config, out: Path) -> Path:
    result = compare_priming(cold, primed)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_priming(result))
    (primed.paths.decisions_dir / "priming.json").write_text(json.dumps(result, indent=2))
    return out
