"""Render a Markdown data card from the raw dataset and its quality report."""

from collections import Counter, defaultdict
from datetime import UTC, datetime

from sathealth.data.download import Manifest
from sathealth.data.schema import AnomalyKind
from sathealth.data.telemanom import TelemanomDataset
from sathealth.features.validation import ChannelStats, QualityReport, Severity

_CHECK_MEANING = {
    "constant_train": "Telemetry never changes in train, so a model cannot learn nominal "
    "variability. Any test movement looks anomalous.",
    "nominal_out_of_range": "Unlabelled test points leave the training range: distribution "
    "shift between the train and test periods. Expect false alarms.",
    "high_anomaly_fraction": "Over 30% of the test series is labelled anomalous, which "
    "inflates point-wise metrics.",
    "low_cardinality": "Discrete or state-like telemetry with few distinct values.",
    "short_train": "Fewer training rows than one window after the validation split.",
    "no_anomalies": "No labelled anomalies, so detection cannot be evaluated here.",
}


def render_data_card(dataset: TelemanomDataset, report: QualityReport, manifest: Manifest) -> str:
    stats = sorted(report.stats, key=lambda s: (s.spacecraft, s.chan_id))
    lines = [
        "# Data card: NASA SMAP & MSL telemetry",
        "",
        f"_Generated by `sathealth report` on {datetime.now(UTC):%Y-%m-%d}. "
        "Do not edit by hand; regenerate with `make report`._",
        "",
        "## Provenance",
        "",
        "| | |",
        "|---|---|",
        f"| Paper | Hundman et al., *Detecting Spacecraft Anomalies Using LSTMs and "
        f"Nonparametric Dynamic Thresholding*, KDD 2018 ({manifest.source.get('paper', '')}) |",
        f"| Original archive | {manifest.source.get('original_url', '')} "
        f"({manifest.source.get('original_status', '')}) |",
        f"| Mirror used | {manifest.source.get('mirror_repo', '')} at commit "
        f"`{manifest.source.get('mirror_commit', '')[:12]}` |",
        f"| Integrity | {len(manifest.files)} files, {manifest.total_bytes / 1e6:.1f} MB, "
        "each pinned by size and SHA-256 in `src/sathealth/data/manifests/telemanom.json` |",
        "| Licence | Telemanom: BSD-3-style, (c) 2018 Caltech/JPL "
        "(https://github.com/khundman/telemanom/blob/master/LICENSE.txt). "
        "Mirror repository: BSD-3-Clause. Cite the paper when using the data. |",
        "",
        "## Structure",
        "",
        "Each channel is one telemetry stream from the spacecraft. Arrays have the shape "
        "`(time, features)`. Column 0 is the telemetry value, already scaled to roughly "
        "[-1, 1] by NASA. The other columns are one-hot flags for commands sent to the "
        "spacecraft. Train series are unlabelled and assumed nominal. Test series carry "
        "expert-labelled anomaly segments (inclusive `[start, end]`) of type *point* or "
        "*contextual*.",
        "",
        "## Summary (after label cleaning)",
        "",
        "| Spacecraft | Channels | Features | Train rows (min–max) | Test rows (min–max) "
        "| Anomaly events | Point / contextual | Test points anomalous |",
        "|---|---:|---:|---|---|---:|---|---:|",
    ]
    by_craft: dict[str, list[ChannelStats]] = defaultdict(list)
    for s in stats:
        by_craft[s.spacecraft].append(s)
    for craft, group in sorted(by_craft.items()):
        kinds: Counter[AnomalyKind] = Counter(
            seg.kind for s in group for seg in dataset.info(s.chan_id).segments
        )
        test_total = sum(s.n_test for s in group)
        anomalous = sum(s.anomaly_fraction * s.n_test for s in group)
        lines.append(
            f"| {craft} | {len(group)} | {group[0].n_features} | "
            f"{min(s.n_train for s in group):,}–{max(s.n_train for s in group):,} | "
            f"{min(s.n_test for s in group):,}–{max(s.n_test for s in group):,} | "
            f"{sum(s.n_segments for s in group)} | "
            f"{kinds[AnomalyKind.POINT]} / {kinds[AnomalyKind.CONTEXTUAL]} | "
            f"{anomalous / test_total:.1%} |"
        )

    lines += ["", "## Label cleaning decisions", ""]
    lines += [f"- {note}" for note in dataset.notes] or ["- None."]
    lines += [
        "- Anomaly sequences are sorted by start index (unsorted in the source for "
        "P-1, E-12 and P-11)."
    ]

    lines += [
        "",
        "## Quality findings",
        "",
        "| Severity | Check | Channels | What it means |",
        "|---|---|---:|---|",
    ]
    grouped: dict[tuple[Severity, str], list[str]] = defaultdict(list)
    for issue in report.issues:
        grouped[(issue.severity, issue.check)].append(issue.chan_id)
    order = {Severity.ERROR: 0, Severity.WARNING: 1, Severity.INFO: 2}
    for (severity, check), chans in sorted(
        grouped.items(), key=lambda kv: (order[kv[0][0]], -len(kv[1]))
    ):
        lines.append(
            f"| {severity.value} | `{check}` | {len(chans)} | {_CHECK_MEANING.get(check, '')} |"
        )
    if not grouped:
        lines.append("| — | — | 0 | No issues found. |")
    lines += [""]
    for (severity, check), chans in sorted(grouped.items(), key=lambda kv: kv[0][1]):
        if severity is not Severity.INFO:
            lines.append(f"- **{check}**: {', '.join(sorted(chans))}")

    lines += [
        "",
        "## Known caveats",
        "",
        "- **Test-set scaling in the source.** Many channels reach exactly ±1.0 in "
        "*test* but not in train, which suggests NASA min-max scaled them with "
        "test-period ranges. We re-fit our own scalers on train rows only, but the "
        "source scaling cannot be undone.",
        "- **Train is not guaranteed clean.** No labels exist for train, so robust "
        "(median/IQR) scaling is used to limit the influence of hidden anomalies.",
        "- **Channel semantics are anonymised.** Prefixes (A, B, C, D, E, F, G, M, P, R, "
        "S, T) group related channels, but NASA did not publish what each measures.",
        "",
        "## Per-channel statistics",
        "",
        "<details><summary>Show all channels</summary>",
        "",
        "| Channel | Craft | Train | Test | Events | Anomalous | Train range "
        "| Nominal out-of-range | Issues |",
        "|---|---|---:|---:|---:|---:|---|---:|---|",
    ]
    issues_by_chan: dict[str, list[str]] = defaultdict(list)
    for issue in report.issues:
        issues_by_chan[issue.chan_id].append(issue.check)
    for s in stats:
        lines.append(
            f"| {s.chan_id} | {s.spacecraft} | {s.n_train:,} | {s.n_test:,} | {s.n_segments} | "
            f"{s.anomaly_fraction:.1%} | [{s.train_min:.3g}, {s.train_max:.3g}] | "
            f"{s.nominal_out_of_range_fraction:.1%} | "
            f"{', '.join(issues_by_chan.get(s.chan_id, [])) or '—'} |"
        )
    lines += ["", "</details>", ""]
    return "\n".join(lines)
